"""Run the full evaluation: classifier on both sets, plus the acceptance tests.

Usage: python scripts/run_eval.py
Writes docs/eval/evaluation_report.json and docs/eval/acceptance_sheet.md
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from copilot.classifier import TaskClassifier, load_split  # noqa: E402
from copilot.evaluation import evaluate_classifier, load_jsonl, run_acceptance_tests  # noqa: E402
from copilot.rag import BM25Index, chunks_from_catalog  # noqa: E402
from copilot.store import Store  # noqa: E402


def main() -> None:
    data = ROOT / "data" / "synthetic"
    train_rows, test_rows = load_split(data)
    model = TaskClassifier.train(train_rows)

    easy = evaluate_classifier(model, test_rows, "held-out templates")
    hard = evaluate_classifier(model, load_jsonl(ROOT / "data" / "eval" / "hard_tasks.jsonl"), "hard paraphrases")

    store = Store.load(data)
    index = BM25Index(chunks_from_catalog(store.catalog, store.brochures))
    acceptance = [r.as_dict() for r in run_acceptance_tests(store, index)]

    out_dir = ROOT / "docs" / "eval"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "evaluation_report.json").write_text(
        json.dumps({"classifier": [easy, hard], "acceptance": acceptance}, indent=2) + "\n", encoding="utf-8"
    )
    (out_dir / "acceptance_sheet.md").write_text(_sheet(acceptance), encoding="utf-8")

    print(f"templates   macro-F1 {easy['macro_f1']:.3f}  (n={easy['n']})")
    print(f"paraphrases macro-F1 {hard['macro_f1']:.3f}  (n={hard['n']}, {len(hard['errors'])} errors)")
    passed = sum(1 for a in acceptance if a["result"] == "PASS")
    print(f"acceptance  {passed}/{len(acceptance)} passed")
    for a in acceptance:
        if a["result"] == "FAIL":
            print(f"  FAIL {a['case']}: {a['actual']}")


def _sheet(acceptance: list[dict]) -> str:
    lines = [
        "# Acceptance test sheet",
        "",
        "Generated by `python scripts/run_eval.py`. Synthetic data only.",
        "",
        "| Case | Action | Expected | Actual | Result | Evidence |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for a in acceptance:
        evidence = ", ".join(f"`{e}`" for e in a["evidence"])
        lines.append(
            f"| {a['case']} | {a['action']} | {a['expected']} | {a['actual']} | **{a['result']}** | {evidence} |"
        )
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    main()
